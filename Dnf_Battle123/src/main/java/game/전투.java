package game;

public class 전투 {
    
    public 캐릭터 캐릭터생성(String 플레이어id, String 캐릭터명, String 직업, int 레벨) {
        플레이어 p = new 플레이어();
        
        if (!p.플레이어체크(플레이어id)) {
            return null; 
        }

        if ("전사".equals(직업)) {
            return new 전사(캐릭터명, 레벨);
        } else if ("마법사".equals(직업)) {
            return new 마법사(캐릭터명, 레벨);
        }
        
        return null;
    }

    public String 몬스터공격(String 플레이어id, 캐릭터 캐릭터객체) {
        플레이어 p = new 플레이어();
        
        if (!p.플레이어체크(플레이어id)) {
            return "[인증 실패] 올바른 플레이어가 아닙니다."; 
        }
        
        if (캐릭터객체 == null) {
            return "[오류] 생성된 캐릭터가 없습니다.";
        }

        // 1. 순차도 명세대로 스킬발동()을 호출하여 데미지만 반환받음
        double 데미지 = 캐릭터객체.스킬발동();
        
        // 2. [추가] 화면 출력을 위해 객체 타입을 검사하여 스킬명을 맵핑
        String 사용스킬 = "";
        if (캐릭터객체 instanceof 전사) {
            사용스킬 = "검휘두르기!";
        } else if (캐릭터객체 instanceof 마법사) {
            사용스킬 = "파이어볼!";
        }

        // 3. 순차도의 등급 판정(alt) 및 최종 메시지 반환
        if (데미지 >= 200) {
            return "🔥 [" + 사용스킬 + "] 명중! 데미지: " + 데미지 + " ➔ [S급 전투 결과]";
        } else if (데미지 >= 100) {
            return "🔥 [" + 사용스킬 + "] 명중! 데미지: " + 데미지 + " ➔ [A급 전투 결과]";
        } else {
            return "🔥 [" + 사용스킬 + "] 명중! 데미지: " + 데미지 + " ➔ [B급 전투 결과]";
        }
    }
        // 기존 메서드들 (캐릭터생성, 몬스터공격) 생략...

        // 신규 추가: 아이템 획득 제어 로직
        public String 아이템획득(String 플레이어id, 캐릭터 캐릭터객체, String 아이템명, String 타입, int 가치) {
            // 1. 반드시 플레이어 체크를 한다 (플레이어id는 "hero")
            if (!"hero".equals(플레이어id)) {
                return "[획득 실패] 올바른 플레이어가 아닙니다.";
            }

            if (캐릭터객체 == null) {
                return "[획득 실패] 캐릭터 정보가 존재하지 않습니다. 캐릭터를 먼저 생성해주세요.";
            }

            // 2. 인벤토리가 가득차면(10개) 아이템을 획득할 수 없다.
            if (캐릭터객체.인벤토리.get현재용량() >= 캐릭터객체.인벤토리.최대용량) {
                return "[획득 실패] 인벤토리가 가득 차 아이템을 획득할 수 없습니다. (최대 10칸)";
            }

            // 3. 아이템의 가치에 따라 등급을 부여한다.
            String 등급 = "일반";
            if (가치 >= 1000) {
                등급 = "전설";
            } else if (가치 >= 500) {
                등급 = "희귀";
            }

            // 4. 아이템 객체 생성 및 캐릭터 인벤토리에 추가 (Composition 구현)
            아이템 신규아이템 = new 아이템(아이템명, 타입, 가치, 등급);
            boolean 결과 = 캐릭터객체.인벤토리.아이템추가(신규아이템);

            if (결과) {
                return "[" + 등급 + "] " + 아이템명 + " (타입: " + 타입 + ", 가치: " + 가치 + ") 획득 성공! " 
                        + "[현재 가방: " + 캐릭터객체.인벤토리.get현재용량() + "/" + 캐릭터객체.인벤토리.최대용량 + "]";
            } else {
                return "[획득 실패] 인벤토리 추가 중 알 수 없는 오류가 발생했습니다.";
            }
        }
    }
